"""High-level iterative execution engine connecting Date Engine, Variables, and Player."""
from __future__ import annotations

import time
from dataclasses import dataclass
from typing import Callable, Optional

from .actions import Action
from .date_engine import DateEngine
from .player import ActionPlayer, PlaybackError
from .safety import SafetyController
from .variables import VariableEngine
from .workflow import Workflow
from ..storage.models import ExecutionLogRecord
from ..storage.project_manager import ProjectManager
from ..utils.logger import get_logger

logger = get_logger("executor")


@dataclass
class ExecutionStats:
    total_iterations: int = 0
    completed_iterations: int = 0
    skipped_iterations: int = 0
    failed_iterations: int = 0
    current_iteration: int = 0
    current_date: str = ""
    current_action_name: str = ""
    is_running: bool = False
    is_dry_run: bool = False


class WorkflowExecutor:
    """
    Executes a Workflow iteratively over the dates provided by the independent Date Engine.
    Substitutes {{STATEMENT_DATE}} and other dynamic variables per iteration.
    """

    def __init__(
        self,
        safety: SafetyController,
        project_manager: Optional[ProjectManager] = None,
        dry_run: bool = False,
    ) -> None:
        self.safety = safety
        self.project_manager = project_manager or ProjectManager()
        self.dry_run = dry_run
        self.stats = ExecutionStats(is_dry_run=dry_run)

        # Callbacks for UI updates
        self.on_iteration_start: Optional[Callable[[int, int, str], None]] = None
        self.on_action_progress: Optional[Callable[[int, int, Action], None]] = None
        self.on_iteration_finish: Optional[Callable[[int, str, bool, str], None]] = None
        self.on_execution_complete: Optional[Callable[[ExecutionStats], None]] = None
        # Error resolution callback returns: "RETRY", "SKIP", or "STOP"
        self.error_resolver: Optional[Callable[[int, str, Action, str], str]] = None

    def run(
        self,
        workflow: Workflow,
        date_engine: DateEngine,
        variable_engine: Optional[VariableEngine] = None,
        project_id: Optional[str] = None,
    ) -> ExecutionStats:
        """Run the workflow once for every date generated by date_engine."""
        var_engine = variable_engine or VariableEngine()
        player = ActionPlayer(safety=self.safety, dry_run=self.dry_run)

        self.safety.reset()
        self.safety.start_global_hotkey_listener()

        date_contexts = list(date_engine.iter_contexts())
        total_dates = len(date_contexts)

        self.stats = ExecutionStats(
            total_iterations=total_dates,
            completed_iterations=0,
            skipped_iterations=0,
            failed_iterations=0,
            current_iteration=0,
            is_running=True,
            is_dry_run=self.dry_run,
        )

        logger.info(
            f"Starting automation for workflow '{workflow.name}' with {total_dates} date iterations (Dry Run: {self.dry_run})"
        )

        try:
            for idx, context in enumerate(date_contexts, start=1):
                if self.safety.is_stopped():
                    logger.warning("Execution loop stopped before iteration.")
                    break

                date_val = context.get("STATEMENT_DATE", f"Iteration_{idx}")
                self.stats.current_iteration = idx
                self.stats.current_date = date_val

                if self.on_iteration_start:
                    self.on_iteration_start(idx, total_dates, date_val)

                iter_start_time = time.time()
                success = False
                error_msg = ""
                output_filename = var_engine.resolve_text(
                    "Statement_{{STATEMENT_DATE}}.pdf", context
                )

                try:
                    # 1. Resolve action variables for this iteration
                    resolved_actions = var_engine.resolve_actions(workflow.actions, context)

                    # 2. Execute actions sequentially
                    act_idx = 0
                    while act_idx < len(resolved_actions):
                        if self.safety.is_stopped():
                            raise PlaybackError("Emergency abort triggered.")

                        act = resolved_actions[act_idx]
                        self.stats.current_action_name = act.display_summary()

                        if self.on_action_progress:
                            self.on_action_progress(act_idx + 1, len(resolved_actions), act)

                        try:
                            player.play_action(act)
                            act_idx += 1
                        except PlaybackError as pe:
                            logger.error(
                                f"Action error on date {date_val}, action #{act_idx + 1} ({act.display_summary()}): {pe}"
                            )
                            # Handle error recovery if resolver is registered
                            decision = "STOP"
                            if self.error_resolver and not self.safety.is_stopped():
                                decision = self.error_resolver(
                                    idx, date_val, act, str(pe)
                                ).upper()

                            if decision == "RETRY":
                                logger.info(f"Retrying action #{act_idx + 1} for date {date_val}")
                                continue  # Retry same act_idx
                            elif decision == "SKIP":
                                logger.warning(f"Skipping remainder of date {date_val}")
                                self.stats.skipped_iterations += 1
                                error_msg = f"Skipped: {pe}"
                                break
                            else:  # STOP or unknown
                                self.safety.trigger_emergency_stop()
                                raise

                    else:
                        # Completed all actions for this date
                        success = True
                        self.stats.completed_iterations += 1

                except Exception as ex:
                    error_msg = str(ex)
                    self.stats.failed_iterations += 1
                    logger.error(f"Iteration {idx} ({date_val}) failed: {ex}")
                    if self.safety.is_stopped():
                        break

                iter_duration = time.time() - iter_start_time

                # Log status in database
                log_status = "SUCCESS" if success else ("SKIPPED" if "Skipped" in error_msg else "FAILED")
                log_rec = ExecutionLogRecord(
                    project_id=project_id,
                    workflow_id=workflow.id,
                    iteration=idx,
                    date_value=date_val,
                    status=log_status,
                    details=error_msg or ("OK (Dry Run)" if self.dry_run else "OK"),
                    output_file=output_filename,
                    duration_sec=iter_duration,
                )
                self.project_manager.log_execution(log_rec)

                if self.on_iteration_finish:
                    self.on_iteration_finish(idx, date_val, success, error_msg)

        finally:
            self.stats.is_running = False
            self.safety.stop_global_hotkey_listener()
            logger.info(
                f"Automation finished: {self.stats.completed_iterations}/{total_dates} succeeded, {self.stats.failed_iterations} failed, {self.stats.skipped_iterations} skipped."
            )
            if self.on_execution_complete:
                self.on_execution_complete(self.stats)

        return self.stats
